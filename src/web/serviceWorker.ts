/**
 * The offline layer.
 *
 * A browser tab is not a guarantee of a network, and an editor that goes
 * blank in a tunnel is not an editor you trust with your work. Everything
 * Tungsten needs to start is stored on the device the first time it is
 * visited; everything else is kept as it is used.
 *
 * This module is pure. It decides *what* to cache and emits the worker's
 * source text; the worker itself is written to `dist/sw.js` by the build.
 * That way the policy is unit-tested in the same suite as everything else,
 * instead of being a file nobody can run.
 */

export type BuiltFile = {
  /** Path relative to the site root, e.g. `assets/App-CX8nAxFi.css`. */
  path: string
  size: number
}

/**
 * Anything larger than this is left to the runtime cache.
 *
 * The TypeScript language worker alone is 6.7 MB. Precaching it would mean
 * a first visit downloading the entire editor toolchain before the page
 * was interactive, over whatever connection the visitor happens to have.
 * It arrives the first time it is actually needed, and is permanent after
 * that.
 */
export const PRECACHE_LIMIT = 1_500_000

/** Paths that are the application shell rather than a feature of it. */
const SHELL = /^(index-|react-vendor-|polyfills-)/

/**
 * Install icons worth storing up front.
 *
 * The 512px and maskable icons are read by the browser when someone
 * installs the app -- an online act by definition -- and the social card
 * is only ever fetched by a crawler. Precaching all three cost 750 kB of
 * a first visit for files the running app never requests.
 */
const ICON_LIMIT = 64_000

/**
 * The install-time list: the smallest set of files that can paint a working
 * page with no network at all.
 *
 * Everything hashed is safe to keep forever, so the cost of being slightly
 * generous here is paid once. Being *too* generous is what makes a first
 * visit feel broken, which is why the size limit exists.
 */
export function choosePrecache(files: BuiltFile[]): string[] {
  const chosen = files.filter((file) => {
    if (file.size > PRECACHE_LIMIT) return false
    if (file.path === 'index.html') return true
    if (file.path === 'manifest.webmanifest') return true
    if (file.path.startsWith('icons/')) {
      return file.path.endsWith('.png') && file.size <= ICON_LIMIT
    }

    const name = file.path.startsWith('assets/') ? file.path.slice('assets/'.length) : ''
    if (!name || name.includes('/')) return false
    // Workers are big, lazy and only needed once a language server starts.
    if (/\.worker-[^.]+\.js$/.test(name)) return false
    if (name.endsWith('.css')) return true
    // Every face ships as both .woff and .woff2 and no browser that can run
    // this app needs the former; storing both doubles the font bill.
    if (/\.(woff2|ttf)$/.test(name)) return true
    if (name.endsWith('.woff')) return false
    return SHELL.test(name) && name.endsWith('.js')
  })

  // Sorted so two builds of the same output produce the same worker, and a
  // diff of sw.js shows real change rather than directory order.
  return ['./', ...chosen.map((file) => file.path).sort()]
}

export function precacheBytes(files: BuiltFile[]): number {
  const paths = new Set(choosePrecache(files))
  return files.filter((file) => paths.has(file.path)).reduce((total, file) => total + file.size, 0)
}

/**
 * A cache name that changes whenever the output changes.
 *
 * Caches are keyed by this and every other one is deleted on activate, so
 * a deploy cannot leave a visitor running half of yesterday's build.
 */
export function cacheName(buildId: string): string {
  return `tungsten-${buildId.replace(/[^a-zA-Z0-9._-]/g, '-')}`
}

export type WorkerOptions = {
  cache: string
  precache: string[]
}

/**
 * The worker's source.
 *
 * Written as one template so the shape of the thing is readable in one
 * screen. Note the three strategies, which are not interchangeable:
 *
 *   navigations   network first, shell as the fallback. A new deploy is
 *                 picked up as soon as there is a network; a tunnel still
 *                 gets the app.
 *   hashed assets cache first. The filename contains the hash of the
 *                 contents, so a hit can never be stale and a miss is
 *                 permanent once stored.
 *   everything    network only. Nothing else here is ours to cache.
 */
export function serviceWorkerSource({ cache, precache }: WorkerOptions): string {
  const list = JSON.stringify(precache, null, 2).replace(/\n/g, '\n')
  return `// Generated by scripts/build-web.mjs -- edit src/web/serviceWorker.ts instead.
const CACHE = ${JSON.stringify(cache)}
const PRECACHE = ${list}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE)
    // Individually, so one 404 cannot fail the whole install.
    await Promise.all(PRECACHE.map(async (path) => {
      try {
        await cache.add(new Request(path, { cache: 'reload' }))
      } catch (error) {
        console.warn('[tungsten] could not precache', path, error)
      }
    }))
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys()
    await Promise.all(keys.filter((key) => key.startsWith('tungsten-') && key !== CACHE)
      .map((key) => caches.delete(key)))
    if (self.registration.navigationPreload) {
      await self.registration.navigationPreload.enable()
    }
    await self.clients.claim()
  })())
})

// The page asks for this once the user agrees to reload, which is the only
// moment it is safe to swap the running build underneath them.
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'tungsten:skip-waiting') self.skipWaiting()
})

const hashed = (url) => url.pathname.includes('/assets/') && /-[A-Za-z0-9_-]{8,}\\.[a-z0-9]+$/.test(url.pathname)

async function fromCache(request) {
  const cache = await caches.open(CACHE)
  const hit = await cache.match(request, { ignoreSearch: true })
  if (hit) return hit
  const response = await fetch(request)
  if (response && response.ok && response.status === 200) cache.put(request, response.clone())
  return response
}

async function shellFirst(event) {
  try {
    const preload = await event.preloadResponse
    const response = preload || await fetch(event.request)
    const cache = await caches.open(CACHE)
    cache.put('./', response.clone())
    return response
  } catch (error) {
    const cache = await caches.open(CACHE)
    const shell = await cache.match('./') || await cache.match('index.html')
    if (shell) return shell
    throw error
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  if (request.mode === 'navigate') {
    event.respondWith(shellFirst(event))
    return
  }
  if (hashed(url) || url.pathname.includes('/icons/')) {
    event.respondWith(fromCache(request))
  }
})
`
}
