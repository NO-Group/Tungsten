#!/usr/bin/env node
/**
 * Generates the Graphene workbench stylesheet.
 *
 * A colour theme can only repaint VS Code. It cannot change the shape of the
 * thing: row heights, tab geometry, the weight and size of type, how focus is
 * expressed, how much air sits between elements. Those are baked into the
 * workbench CSS, and they are most of what makes an editor feel like itself.
 *
 * This file is the structural half of the redesign. It is generated from the
 * same tokens.json as the colour theme, so the two cannot drift.
 *
 * The output is appended to VS Code's own style.css between sentinel markers,
 * which means it wins on cascade order without needing a fragile line-based
 * patch against upstream source that would break on every rebase.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const tokens = JSON.parse(readFileSync(resolve(here, 'tokens.json'), 'utf8'))

export const BEGIN_MARKER = '/* >>> GRAPHENE BEGIN — generated by fork/graphene/buildWorkbenchCss.mjs. Do not edit by hand. <<< */'
export const END_MARKER = '/* >>> GRAPHENE END <<< */'

