/**
 * The backend, written for you.
 *
 * Every other target in this folder produces a front end and then hands it
 * three stubs -- `Api`, `Auth`, `Storage` -- that print what they would
 * have done. This emitter writes the thing on the other end of those
 * calls: one Node service with accounts, a table per box drawn in the
 * schema editor, and somewhere to put files.
 *
 * Three rules shaped it.
 *
 * No dependencies. Node 22 ships an HTTP server, a crypto library and, as
 * of 22.5, SQLite; a generated backend whose first instruction is `npm
 * install` is a generated backend that breaks the week some package three
 * levels down is yanked. `node server/main.js` is the whole setup.
 *
 * One service for all six targets. The Kotlin app, the Swift app, the
 * Flutter app and the two desktop shells talk to the same URLs, so the
 * answer to "does the Android build agree with the iOS build" is yes by
 * construction rather than by discipline.
 *
 * Nothing invented. Tables, columns and their types come from the visual
 * schema; the service refuses any table or column that was not drawn.
 * That is also the injection defence: identifiers are looked up in a
 * generated map and values are always bound parameters.
 */

import { safeName, type DataSchema, type Table } from '../dataSchema'
import { slug, type Project } from '../../project/targets'
import type { CompiledFile } from '../compile'

/** Where the generated clients look for this service unless told otherwise. */
export const DEFAULT_API_URL = 'http://localhost:8787'

/** The port that URL implies. */
export const DEFAULT_API_PORT = 8787

/**
 * SQLite column types, which are not the ones `createMigration` writes.
 *
 * That function targets Postgres, and this one cannot: `bigserial`,
 * `timestamptz` and `jsonb` are all syntax errors here. Two dialects for
 * two different places rather than one dialect that is wrong in both.
 */
const SQLITE_TYPE: Record<string, string> = {
  text: 'text',
  number: 'real',
  boolean: 'integer',
  timestamp: 'text',
  json: 'text',
}

/** The columns a drawn table actually gets, after cleaning the names. */
function columnsOf(table: Table): Array<{ name: string; type: string; required: boolean; unique: boolean }> {
  return table.columns.map((column, index) => ({
    name: safeName(column.name, `column_${index + 1}`),
    type: column.type,
    required: Boolean(column.required),
    unique: Boolean(column.unique),
  }))
}

/** The schema editor's boxes, as SQLite. */
export function sqliteSchema(schema: DataSchema): string {
  const header = `-- Generated by the Tungsten builder from the visual schema.
-- Applied at boot, every boot: every statement is "if not exists", so
-- restarting the service never costs you a row.

create table if not exists users (
  id text primary key,
  email text not null unique,
  password_hash text,
  provider text,
  created_at text not null default (datetime('now'))
);

create table if not exists sessions (
  token text primary key,
  user_id text not null references users(id),
  created_at text not null default (datetime('now'))
);

create table if not exists files (
  id text primary key,
  bucket text not null,
  name text not null,
  size integer not null,
  created_at text not null default (datetime('now'))
);
`

  const tables = schema.tables.map((table, index) => {
    const name = safeName(table.name, `table_${index + 1}`)
    const columns = [
      '  id integer primary key autoincrement',
      ...columnsOf(table).map((column) => {
        const parts = [`  ${column.name} ${SQLITE_TYPE[column.type] ?? 'text'}`]
        if (column.required) parts.push('not null')
        if (column.unique) parts.push('unique')
        return parts.join(' ')
      }),
      "  created_at text not null default (datetime('now'))",
    ]
    return `create table if not exists ${name} (\n${columns.join(',\n')}\n);`
  })

  return tables.length
    ? `${header}\n${tables.join('\n\n')}\n`
    : `${header}\n-- No tables drawn yet. Draw one in the Data tab and build again.\n`
}

/** What the service will accept, as data the router can check against. */
function tableMap(schema: DataSchema): string {
  const entries = schema.tables.map((table, index) => {
    const name = safeName(table.name, `table_${index + 1}`)
    const columns = columnsOf(table).map((column) => `'${column.name}'`).join(', ')
    return `  ${JSON.stringify(name)}: [${columns}],`
  })
  return entries.length ? `{\n${entries.join('\n')}\n}` : '{}'
}

/**
 * The service itself.
 *
 * Deliberately one file. It is around four hundred lines, every one of
 * them readable, and a generated backend split across a dozen modules is
 * a generated backend nobody reads before running it.
 */
function mainJs(schema: DataSchema, project: Project): string {
  return `// ${project.name} — backend service, generated by the Tungsten builder.
//
// Run it:   node main.js
// Needs:    Node 22.5 or newer (node:sqlite arrived there). Nothing else.
//
// Environment:
//   PORT                    default ${DEFAULT_API_PORT}
//   TUNGSTEN_DB             default ./data.sqlite
//   TUNGSTEN_UPLOADS        default ./uploads
//   TUNGSTEN_REQUIRE_AUTH   1 to make every write need a signed-in user
//   TUNGSTEN_ORIGIN         allowed browser origin, default *
//   TUNGSTEN_OAUTH_REDIRECT where to send the browser after an OAuth round trip
//   GITHUB_CLIENT_ID / GITHUB_CLIENT_SECRET
//   GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET

import { createServer } from 'node:http'
import { DatabaseSync } from 'node:sqlite'
import { randomUUID, randomBytes, scryptSync, timingSafeEqual } from 'node:crypto'
import { readFileSync, mkdirSync, writeFileSync, createReadStream, existsSync, statSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const port = Number(process.env.PORT ?? ${DEFAULT_API_PORT})
const origin = process.env.TUNGSTEN_ORIGIN ?? '*'
const requireAuth = process.env.TUNGSTEN_REQUIRE_AUTH === '1'
const uploads = resolve(process.env.TUNGSTEN_UPLOADS ?? join(here, 'uploads'))

// ----------------------------------------------------------- the database

const db = new DatabaseSync(process.env.TUNGSTEN_DB ?? join(here, 'data.sqlite'))
db.exec('pragma journal_mode = WAL')
db.exec('pragma foreign_keys = ON')
db.exec(readFileSync(join(here, 'schema.sql'), 'utf8'))

/**
 * The tables this service will touch, and the columns each one has.
 *
 * Generated from the visual schema. Nothing outside this map reaches SQL:
 * a request naming a table that was never drawn is a 404, and a field
 * that is not a column of that table is dropped rather than interpolated.
 */
const TABLES = ${tableMap(schema)}

const query = (sql, ...values) => db.prepare(sql).all(...values)
const run = (sql, ...values) => db.prepare(sql).run(...values)
const one = (sql, ...values) => db.prepare(sql).get(...values)

// -------------------------------------------------------------- accounts

/**
 * Passwords are salted and hashed with scrypt, never stored or logged.
 *
 * scrypt rather than a single SHA pass because the whole point is to be
 * slow: a leaked table of fast hashes is a leaked table of passwords.
 */
function hashPassword(password) {
  const salt = randomBytes(16).toString('hex')
  return salt + ':' + scryptSync(password, salt, 64).toString('hex')
}

function passwordMatches(password, stored) {
  if (typeof stored !== 'string' || !stored.includes(':')) return false
  const [salt, expected] = stored.split(':')
  const actual = scryptSync(password, salt, 64).toString('hex')
  // Constant time, so the comparison does not leak the prefix it matched.
  const a = Buffer.from(actual, 'hex')
  const b = Buffer.from(expected, 'hex')
  return a.length === b.length && timingSafeEqual(a, b)
}

function createSession(userId) {
  const token = randomBytes(32).toString('hex')
  run('insert into sessions (token, user_id) values (?, ?)', token, userId)
  return token
}

function userFor(request) {
  const header = request.headers.authorization ?? ''
  const token = header.startsWith('Bearer ') ? header.slice(7) : ''
  if (!token) return null
  const row = one(
    'select users.id as id, users.email as email, users.provider as provider' +
    ' from sessions join users on users.id = sessions.user_id where sessions.token = ?',
    token,
  )
  return row ?? null
}

function publicUser(row) {
  return { id: row.id, email: row.email, provider: row.provider ?? 'password' }
}

// ---------------------------------------------------------------- replies

function send(response, status, body, headers = {}) {
  const payload = JSON.stringify(body ?? {})
  response.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'access-control-allow-origin': origin,
    'access-control-allow-headers': 'content-type, authorization, x-file-name',
    'access-control-allow-methods': 'GET, POST, PATCH, DELETE, OPTIONS',
    'cache-control': 'no-store',
    ...headers,
  })
  response.end(payload)
}

const fail = (response, status, message) => send(response, status, { error: message })

/** At most a megabyte of JSON, because a body with no limit is a way in. */
async function readJson(request) {
  const chunks = []
  let size = 0
  for await (const chunk of request) {
    size += chunk.length
    if (size > 1_000_000) throw new Error('Body too large')
    chunks.push(chunk)
  }
  if (!chunks.length) return {}
  try {
    const parsed = JSON.parse(Buffer.concat(chunks).toString('utf8'))
    return parsed && typeof parsed === 'object' ? parsed : {}
  } catch {
    throw new Error('Body is not JSON')
  }
}

async function readBytes(request, limit = 25_000_000) {
  const chunks = []
  let size = 0
  for await (const chunk of request) {
    size += chunk.length
    if (size > limit) throw new Error('File too large')
    chunks.push(chunk)
  }
  return Buffer.concat(chunks)
}

// ------------------------------------------------------------------ CRUD

/** Only the fields that are really columns of that table, in order. */
function fieldsOf(table, body) {
  const allowed = TABLES[table] ?? []
  return allowed.filter((column) => Object.prototype.hasOwnProperty.call(body, column))
}

function coerce(value) {
  if (value === null || value === undefined) return null
  if (typeof value === 'boolean') return value ? 1 : 0
  if (typeof value === 'number' || typeof value === 'string') return value
  return JSON.stringify(value)
}

function listRows(table, url) {
  const allowed = TABLES[table]
  const filters = []
  const values = []
  for (const [key, value] of url.searchParams) {
    if (!allowed.includes(key)) continue
    filters.push(key + ' = ?')
    values.push(value)
  }
  const limit = Math.min(Number(url.searchParams.get('limit') ?? 100) || 100, 1000)
  const offset = Math.max(Number(url.searchParams.get('offset') ?? 0) || 0, 0)
  const order = allowed.includes(url.searchParams.get('order') ?? '') ? url.searchParams.get('order') : 'id'
  const where = filters.length ? ' where ' + filters.join(' and ') : ''
  return query(
    'select * from ' + table + where + ' order by ' + order + ' limit ? offset ?',
    ...values,
    limit,
    offset,
  )
}

// ----------------------------------------------------------------- OAuth

const PROVIDERS = {
  github: {
    authorize: 'https://github.com/login/oauth/authorize',
    token: 'https://github.com/login/oauth/access_token',
    profile: 'https://api.github.com/user',
    scope: 'read:user user:email',
  },
  google: {
    authorize: 'https://accounts.google.com/o/oauth2/v2/auth',
    token: 'https://oauth2.googleapis.com/token',
    profile: 'https://www.googleapis.com/oauth2/v3/userinfo',
    scope: 'openid email',
  },
}

const clientId = (provider) => process.env[provider.toUpperCase() + '_CLIENT_ID'] ?? ''
const clientSecret = (provider) => process.env[provider.toUpperCase() + '_CLIENT_SECRET'] ?? ''
const callbackUrl = (provider, request) => {
  const host = request.headers.host ?? 'localhost:' + port
  return 'http://' + host + '/auth/callback/' + provider
}

/**
 * Finishes the round trip.
 *
 * The provider sends the browser back with a code; this swaps it for a
 * token, asks who that is, and makes a local account with the same email.
 * No provider tokens are kept: the app gets a session of its own.
 */
async function completeOAuth(provider, code, request) {
  const config = PROVIDERS[provider]
  const body = new URLSearchParams({
    client_id: clientId(provider),
    client_secret: clientSecret(provider),
    code,
    redirect_uri: callbackUrl(provider, request),
    grant_type: 'authorization_code',
  })
  const exchanged = await fetch(config.token, {
    method: 'POST',
    headers: { accept: 'application/json', 'content-type': 'application/x-www-form-urlencoded' },
    body,
  })
  const granted = await exchanged.json()
  if (!granted.access_token) throw new Error('The provider refused the code')

  const profile = await (await fetch(config.profile, {
    headers: { accept: 'application/json', authorization: 'Bearer ' + granted.access_token, 'user-agent': 'tungsten' },
  })).json()

  const email = profile.email ?? profile.login + '@' + provider + '.local'
  let user = one('select * from users where email = ?', email)
  if (!user) {
    const id = randomUUID()
    run('insert into users (id, email, provider) values (?, ?, ?)', id, email, provider)
    user = one('select * from users where id = ?', id)
  }
  return { token: createSession(user.id), user: publicUser(user) }
}

// ---------------------------------------------------------------- routing

const server = createServer(async (request, response) => {
  const url = new URL(request.url ?? '/', 'http://' + (request.headers.host ?? 'localhost'))
  const path = url.pathname.replace(/\\/+$/, '') || '/'
  const parts = path.split('/').filter(Boolean)
  const method = request.method ?? 'GET'

  if (method === 'OPTIONS') return send(response, 204, null)

  try {
    if (path === '/' || path === '/health') {
      return send(response, 200, { ok: true, service: ${JSON.stringify(project.name)}, tables: Object.keys(TABLES) })
    }

    // ---- accounts

    if (path === '/auth/sign-up' && method === 'POST') {
      const body = await readJson(request)
      const email = String(body.email ?? '').trim().toLowerCase()
      const password = String(body.password ?? '')
      if (!email.includes('@')) return fail(response, 400, 'That is not an email address.')
      if (password.length < 8) return fail(response, 400, 'Use at least eight characters.')
      if (one('select id from users where email = ?', email)) {
        return fail(response, 409, 'That email already has an account.')
      }
      const id = randomUUID()
      run('insert into users (id, email, password_hash, provider) values (?, ?, ?, ?)',
        id, email, hashPassword(password), 'password')
      const user = one('select * from users where id = ?', id)
      return send(response, 201, { token: createSession(id), user: publicUser(user) })
    }

    if (path === '/auth/sign-in' && method === 'POST') {
      const body = await readJson(request)
      const email = String(body.email ?? '').trim().toLowerCase()
      const user = one('select * from users where email = ?', email)
      // One message for both halves: saying which was wrong tells an
      // attacker which emails have accounts.
      if (!user || !passwordMatches(String(body.password ?? ''), user.password_hash)) {
        return fail(response, 401, 'That email and password do not match.')
      }
      return send(response, 200, { token: createSession(user.id), user: publicUser(user) })
    }

    if (path === '/auth/session' && method === 'GET') {
      const user = userFor(request)
      return send(response, 200, user ? { user: publicUser(user) } : {})
    }

    if (path === '/auth/sign-out' && method === 'POST') {
      const header = request.headers.authorization ?? ''
      if (header.startsWith('Bearer ')) run('delete from sessions where token = ?', header.slice(7))
      return send(response, 200, { ok: true })
    }

    if (path === '/auth/oauth' && method === 'POST') {
      const body = await readJson(request)
      const provider = String(body.provider ?? '').toLowerCase()
      const config = PROVIDERS[provider]
      if (!config) return fail(response, 400, 'Unknown provider: ' + provider)
      if (!clientId(provider)) {
        return fail(response, 501, 'Set ' + provider.toUpperCase() + '_CLIENT_ID and _CLIENT_SECRET first.')
      }
      const authorize = new URL(config.authorize)
      authorize.searchParams.set('client_id', clientId(provider))
      authorize.searchParams.set('redirect_uri', callbackUrl(provider, request))
      authorize.searchParams.set('response_type', 'code')
      authorize.searchParams.set('scope', config.scope)
      authorize.searchParams.set('state', randomBytes(8).toString('hex'))
      // The app opens this; the browser comes back to /auth/callback.
      return send(response, 200, { url: authorize.toString(), provider })
    }

    if (parts[0] === 'auth' && parts[1] === 'callback' && method === 'GET') {
      const provider = parts[2] ?? ''
      if (!PROVIDERS[provider]) return fail(response, 404, 'Unknown provider.')
      const code = url.searchParams.get('code')
      if (!code) return fail(response, 400, 'No code came back from the provider.')
      const session = await completeOAuth(provider, code, request)
      const back = process.env.TUNGSTEN_OAUTH_REDIRECT
      if (back) {
        return send(response, 302, session, { location: back + '#token=' + session.token })
      }
      return send(response, 200, session)
    }

    // ---- the drawn tables

    if (parts[0] === 'data') {
      const table = parts[1] ?? ''
      if (!Object.prototype.hasOwnProperty.call(TABLES, table)) {
        return fail(response, 404, 'No table called ' + table + ' was drawn in the schema.')
      }
      const writing = method !== 'GET'
      if (writing && requireAuth && !userFor(request)) return fail(response, 401, 'Sign in first.')
      const id = parts[2]

      if (method === 'GET' && !id) return send(response, 200, { rows: listRows(table, url) })

      if (method === 'GET') {
        const row = one('select * from ' + table + ' where id = ?', id)
        return row ? send(response, 200, { row }) : fail(response, 404, 'No row with that id.')
      }

      if (method === 'POST') {
        const body = await readJson(request)
        const fields = fieldsOf(table, body)
        if (!fields.length) return fail(response, 400, 'None of those fields are columns of ' + table + '.')
        const placeholders = fields.map(() => '?').join(', ')
        const result = run(
          'insert into ' + table + ' (' + fields.join(', ') + ') values (' + placeholders + ')',
          ...fields.map((field) => coerce(body[field])),
        )
        const row = one('select * from ' + table + ' where id = ?', result.lastInsertRowid)
        return send(response, 201, { row })
      }

      if (method === 'PATCH' && id) {
        const body = await readJson(request)
        const fields = fieldsOf(table, body)
        if (!fields.length) return fail(response, 400, 'Nothing to change.')
        run(
          'update ' + table + ' set ' + fields.map((field) => field + ' = ?').join(', ') + ' where id = ?',
          ...fields.map((field) => coerce(body[field])),
          id,
        )
        return send(response, 200, { row: one('select * from ' + table + ' where id = ?', id) })
      }

      if (method === 'DELETE' && id) {
        run('delete from ' + table + ' where id = ?', id)
        return send(response, 200, { ok: true })
      }

      return fail(response, 405, method + ' is not allowed here.')
    }

    // ---- files

    if (parts[0] === 'storage') {
      const bucket = (parts[1] ?? '').replace(/[^a-z0-9_-]/gi, '')
      if (!bucket) return fail(response, 400, 'Name a bucket.')

      if (method === 'POST') {
        if (requireAuth && !userFor(request)) return fail(response, 401, 'Sign in first.')
        const bytes = await readBytes(request)
        if (!bytes.length) return fail(response, 400, 'The upload was empty.')
        // The stored name is generated, never the one the client sent: a
        // caller must not get to choose where on disk their bytes land.
        const given = String(request.headers['x-file-name'] ?? 'upload')
        const name = randomUUID() + (extname(given).slice(0, 10) || '')
        mkdirSync(join(uploads, bucket), { recursive: true })
        writeFileSync(join(uploads, bucket, name), bytes)
        run('insert into files (id, bucket, name, size) values (?, ?, ?, ?)',
          randomUUID(), bucket, name, bytes.length)
        const host = request.headers.host ?? 'localhost:' + port
        return send(response, 201, {
          url: 'http://' + host + '/storage/' + bucket + '/' + name,
          name,
          size: bytes.length,
        })
      }

      if (method === 'GET' && parts[2]) {
        const name = parts[2].replace(/[^a-z0-9._-]/gi, '')
        const file = join(uploads, bucket, name)
        if (!file.startsWith(uploads) || !existsSync(file)) return fail(response, 404, 'No such file.')
        response.writeHead(200, {
          'content-type': 'application/octet-stream',
          'content-length': statSync(file).size,
          'access-control-allow-origin': origin,
        })
        return createReadStream(file).pipe(response)
      }

      return fail(response, 405, method + ' is not allowed here.')
    }

    return fail(response, 404, 'No route for ' + method + ' ' + path + '.')
  } catch (error) {
    // The message is ours or the body reader's, never a stack trace.
    return fail(response, 400, error instanceof Error ? error.message : 'Something went wrong.')
  }
})

server.listen(port, () => {
  console.log('${project.name} backend on http://localhost:' + port)
  console.log('Tables: ' + (Object.keys(TABLES).join(', ') || 'none drawn yet'))
  if (!requireAuth) console.log('Writes are open. Set TUNGSTEN_REQUIRE_AUTH=1 before this leaves your machine.')
})
`
}

function readme(schema: DataSchema, project: Project): string {
  const tables = schema.tables.map((table, index) => safeName(table.name, `table_${index + 1}`))
  const routes = tables.length
    ? tables.map((table) => `| \`/data/${table}\` | GET, POST, PATCH, DELETE | the ${table} table |`).join('\n')
    : '| — | — | no tables drawn yet |'

  return `# ${project.name} — backend service

Generated by the Tungsten builder from the blocks and the visual schema.
One file, no dependencies, SQLite on disk.

\`\`\`bash
node main.js              # http://localhost:${DEFAULT_API_PORT}
\`\`\`

Node 22.5 or newer, because \`node:sqlite\` is built in from there. There is
nothing to install.

## What it answers

| Route | Methods | What it is |
| --- | --- | --- |
| \`/health\` | GET | is it up, and which tables it knows |
| \`/auth/sign-up\` | POST | email and password, returns a session token |
| \`/auth/sign-in\` | POST | the same, for an account that exists |
| \`/auth/session\` | GET | who the bearer token belongs to |
| \`/auth/sign-out\` | POST | forgets the token |
| \`/auth/oauth\` | POST | starts a GitHub or Google round trip |
| \`/storage/:bucket\` | POST, GET | files in, files out |
${routes}

Every write takes JSON and returns JSON. Send the token as
\`Authorization: Bearer <token>\`; the generated apps already do.

## The tables

They are the boxes you drew in the Data tab, turned into \`schema.sql\` and
applied at boot. Add a column there, build again, restart: SQLite picks up
the new \`create table if not exists\` without touching your rows. The
service will not read or write a table or a column that is not in that
file.

## Before it leaves your machine

- \`TUNGSTEN_REQUIRE_AUTH=1\` makes every write need a signed-in user. It is
  off by default so the first run works; turn it on before anyone else can
  reach the port.
- \`TUNGSTEN_ORIGIN=https://your.app\` instead of the \`*\` it answers with now.
- Put it behind TLS. Passwords are scrypt-hashed in the database, which
  does nothing for them in flight.
- \`TUNGSTEN_DB\` and \`TUNGSTEN_UPLOADS\` decide where the data lives. Back up
  both or neither; a row pointing at a file that is gone is worse than
  having lost both.

## OAuth

\`\`\`bash
GITHUB_CLIENT_ID=... GITHUB_CLIENT_SECRET=... node main.js
\`\`\`

Register \`http://localhost:${DEFAULT_API_PORT}/auth/callback/github\` as the callback.
Google works the same way with \`GOOGLE_\` variables. No provider tokens are
stored: the round trip ends with an account and a session of this
service's own.
`
}

