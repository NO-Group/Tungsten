/* ------------------------------------------------------------------ *
 * Injection
 * ------------------------------------------------------------------ */

/**
 * Idempotently splices the Graphene block into an upstream stylesheet.
 * Re-running replaces the previous block rather than stacking copies,
 * so the fork script can be run any number of times on the same tree.
 */
export function injectInto(source, css) {
  const begin = source.indexOf(BEGIN_MARKER)
  if (begin === -1) return `${source.trimEnd()}\n\n${css}`

  const end = source.indexOf(END_MARKER, begin)
  if (end === -1) throw new Error('found a Graphene begin marker with no matching end marker')
  return `${source.slice(0, begin)}${css.trim()}${source.slice(end + END_MARKER.length)}`
}

/** Cheap structural checks — enough to catch a generator that emitted garbage. */
export function validateCss(css) {
  const issues = []
  const body = css.slice(css.indexOf(BEGIN_MARKER) + BEGIN_MARKER.length, css.indexOf(END_MARKER))

  const opens = (body.match(/\{/g) ?? []).length
  const closes = (body.match(/\}/g) ?? []).length
  if (opens !== closes) issues.push(`unbalanced braces: ${opens} open, ${closes} close`)

  if (/undefined|\[object Object\]|NaN/.test(body)) {
    issues.push('output contains an unresolved template value (undefined/NaN/[object Object])')
  }

  // Every colour literal must be a real hex value.
  for (const hex of body.match(/#[0-9a-fA-F]*/g) ?? []) {
    if (!/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/.test(hex)) {
      issues.push(`malformed colour literal: ${hex}`)
    }
  }

  if (!body.includes('--graphene-accent:')) issues.push('accent custom property missing')

  return issues
}

/* ------------------------------------------------------------------ *
 * CLI
 * ------------------------------------------------------------------ */

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const css = buildWorkbenchCss()
  const issues = validateCss(css)
  if (issues.length > 0) {
    for (const issue of issues) console.error(`  ! ${issue}`)
    process.exit(1)
  }
  if (process.argv.includes('--check')) {
    console.log(`graphene.css ok — ${css.split('\n').length} lines, ${(css.match(/\{/g) ?? []).length} rules`)
  } else {
    const out = resolve(here, 'dist')
    mkdirSync(out, { recursive: true })
    writeFileSync(resolve(out, 'graphene.css'), css)
    console.log(`wrote ${resolve(out, 'graphene.css')}`)
    console.log(`  ${css.split('\n').length} lines, ${(css.match(/\{/g) ?? []).length} rules`)
  }
}
